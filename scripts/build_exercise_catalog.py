"""Build src/shared/exerciseCatalog.js from free-exercise-db (public domain) + Korean translations.

Usage: python3 scripts/build_exercise_catalog.py <exercises.json> <items.json> <translations_dir> <out.js>
  exercises.json   https://github.com/yuhonas/free-exercise-db (dist/exercises.json)
  items.json       filtered list with app ids (strength-type exercises, minus the hand-written ones)
  translations_dir chunk_N.ko.json files: [{id, ko, tips[]}]
"""
import glob
import json
import sys

EQUIPMENT = {
    'barbell': 'barbell', 'e-z curl bar': 'barbell', 'dumbbell': 'dumbbell', 'kettlebells': 'kettlebell',
    'bands': 'band', 'medicine ball': 'medicine_ball', 'other': 'other', 'machine': 'machine', 'cable': 'cable',
    'body only': 'bodyweight', None: 'bodyweight', 'exercise ball': 'ball', 'foam roll': 'bodyweight',
}
INCREMENT = {'barbell': 2.5, 'dumbbell': 2, 'kettlebell': 4, 'machine': 5, 'cable': 2.5, 'other': 2.5,
             'band': 0, 'medicine_ball': 1, 'bodyweight': 0, 'ball': 0}
ICON = {'barbell': 'barbell', 'dumbbell': 'generic', 'kettlebell': 'kettlebell', 'machine': 'machine', 'cable': 'machine',
        'bodyweight': 'bodyweight', 'ball': 'bodyweight', 'band': 'generic', 'medicine_ball': 'generic', 'other': 'barbell'}
MUSCLE = {'abdominals': 'abs', 'abductors': 'glutes', 'adductors': 'adductors', 'biceps': 'biceps', 'calves': 'calves',
          'chest': 'chest', 'forearms': 'forearms', 'glutes': 'glutes', 'hamstrings': 'hamstrings', 'lats': 'lats',
          'lower back': 'lower_back', 'middle back': 'upper_back', 'neck': 'traps', 'quadriceps': 'quads',
          'traps': 'traps', 'triceps': 'triceps'}
# Names that two translations shared; made distinct by hand.
NAME_OVERRIDES = {'bent_over_two_arm_long_bar_row': '랜드마인 T바 로우 (투암)', 'push_ups_with_feet_elevated': '발 올린 푸시업'}


def shoulder(name):
    n = name.lower()
    if 'rear' in n or 'reverse fly' in n or 'face pull' in n or 'bent over lateral' in n:
        return 'rear_delts'
    if 'lateral' in n or 'side' in n or 'upright' in n:
        return 'side_delts'
    return 'front_delts'


def muscles(ms, name):
    out = []
    for m in ms:
        v = shoulder(name) if m == 'shoulders' else MUSCLE.get(m)
        if v and v not in out:
            out.append(v)
    return out


def main(dataset, items_path, tdir, out):
    src = {x['name']: x for x in json.load(open(dataset))}
    items = json.load(open(items_path))
    ko = {}
    for f in sorted(glob.glob(f'{tdir}/chunk_*.ko.json')):
        for x in json.load(open(f)):
            ko[x['id']] = x
    catalog = []
    for it in items:
        t = ko[it['id']]
        x = src[it['name']]
        eq = EQUIPMENT.get(x.get('equipment'), 'other')
        primary = muscles(x['primaryMuscles'], x['name'])
        secondary = [m for m in muscles(x['secondaryMuscles'], x['name']) if m not in primary]
        catalog.append({
            'id': it['id'],
            'name': NAME_OVERRIDES.get(it['id'], t['ko']),
            'aliases': [x['name']],
            'icon': ICON[eq],
            'equipment': eq,
            'increment': INCREMENT[eq],
            'level': x.get('level'),
            'muscles': {'primary': primary, 'secondary': secondary},
            'tips': t['tips'],
        })
    names = [c['name'] for c in catalog]
    assert len(names) == len(set(names)), 'duplicate names'
    header = ('// Generated by scripts/build_exercise_catalog.py — do not edit by hand.\n'
              '// Source: free-exercise-db (public domain, https://github.com/yuhonas/free-exercise-db),\n'
              '// strength-type exercises, names and form tips translated to Korean.\n')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(header + 'export const CATALOG = ' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{len(catalog)} exercises -> {out}')


if __name__ == '__main__':
    main(*sys.argv[1:5])
